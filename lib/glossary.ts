/** 本文(HTMLを除いたテキスト)に出てくる用語を、出現順に最大 max 件返す */
export function termsIn(text: string, max = 8): Term[] {
  const found: { t: Term; i: number }[] = [];
  for (const t of GLOSSARY) {
    const keys = [t.term, ...(t.aliases ?? [])];
    const idx = keys.map((k) => text.indexOf(k)).filter((i) => i >= 0);
    if (idx.length) found.push({ t, i: Math.min(...idx) });
  }
  return found.sort((a, b) => a.i - b.i).slice(0, max).map((f) => f.t);
}
